export type I18nCopy = (typeof i18n)[Locale];

export function getI18n(locale: Locale): I18nCopy {
  return i18n[locale];
}

export function formatI18n(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}
